// MediaMTX configuration generator (pure). Field names checked against the mediamtx.yml shipped
// with v1.21.2: https://github.com/bluenviron/mediamtx/blob/v1.21.2/mediamtx.yml
// MediaMTX rejects unknown keys, so only emit fields that exist in the pinned version.

import { FEEDS } from '../../../shared/types.js';
import { feedPath, GUEST_PATHS_REGEX, PROFILE_PATHS_REGEX } from './paths.js';

export interface MediaMtxConfigOptions {
  /** RTMP ingest port (all interfaces; OBS is on the LAN). */
  rtmpPort: number;
  /** Control API port (bound to 127.0.0.1). */
  apiPort: number;
  /** Port of our loopback auth server (POST /auth). */
  authPort: number;
  /**
   * Low-Latency HLS port for the live preview (bound to 127.0.0.1; Relay's own HTTP server proxies
   * it with the internal reader password). null/undefined = HLS off.
   */
  hlsPort?: number | null;
  logLevel?: 'error' | 'warn' | 'info' | 'debug';
}

function q(value: string): string {
  return JSON.stringify(value); // a JSON string is a valid double-quoted YAML scalar
}

function port(n: number, name: string): number {
  if (!Number.isInteger(n) || n < 1 || n > 65535) throw new Error(`Invalid ${name}: ${n}`);
  return n;
}

export function buildMediaMtxConfig(opts: MediaMtxConfigOptions): string {
  const rtmpPort = port(opts.rtmpPort, 'rtmpPort');
  const apiPort = port(opts.apiPort, 'apiPort');
  const authPort = port(opts.authPort, 'authPort');
  const hlsPort = opts.hlsPort === null || opts.hlsPort === undefined ? null : port(opts.hlsPort, 'hlsPort');

  const lines = [
    '# Generated by CTD Relay on every start. Manual edits are overwritten.',
    '',
    `logLevel: ${opts.logLevel ?? 'info'}`,
    'logDestinations: [stdout]',
    'logStructured: false',
    'readTimeout: 10s',
    'writeTimeout: 10s',
    '',
    '# Every publish/read is decided by the app (loopback HTTP). The API is loopback-only.',
    'authMethod: http',
    `authHTTPAddress: ${q(`http://127.0.0.1:${authPort}/auth`)}`,
    'authHTTPExclude:',
    '  - action: api',
    '  - action: metrics',
    '',
    'api: true',
    `apiAddress: ${q(`127.0.0.1:${apiPort}`)}`,
    'metrics: false',
    'pprof: false',
    'playback: false',
    '',
    'rtmp: true',
    'rtmpEncryption: "no"',
    `rtmpAddress: ${q(`:${rtmpPort}`)}`,
    '',
    'rtsp: false',
    ...hlsLines(hlsPort),
    'webrtc: false',
    'srt: false',
    'moq: false',
    '',
    'pathDefaults:',
    '  source: publisher',
    '  # Lets OBS reconnect while its previous (dead) connection is still being torn down.',
    '  overridePublisher: true',
    '  record: false',
    '',
    '# The default profile keeps live/landscape + live/vertical; every other profile publishes to',
    '# live/<slug>/landscape + live/<slug>/vertical (one regex, so new profiles need no restart; the',
    '# auth hook only accepts slugs of existing profiles). Any other path is rejected by MediaMTX.',
    'paths:',
    ...FEEDS.flatMap((feed) => [`  ${feedPath(feed)}:`, '    source: publisher']),
    `  ${q(PROFILE_PATHS_REGEX)}:`,
    '    source: publisher',
    '# Guest feeds (docs/API.md §18): guest/<slot>, one regex; the auth hook only accepts existing',
    '# slots with their own key. Read back only by Relay (LL-HLS preview, thumbnails), never pushed.',
    `  ${q(GUEST_PATHS_REGEX)}:`,
    '    source: publisher',
    '',
  ];
  return lines.join('\n');
}

/**
 * The live preview (docs/PREVIEW.md): Low-Latency HLS, loopback only, muxed on demand. The H.264 +
 * AAC tracks are copied into fMP4 parts (no transcoding); a muxer starts on the first request and
 * closes 30 s after the last one. Segments live in RAM (hlsDirectory empty), at most 7 of them.
 * hlsAllowOrigins is empty: browsers never reach MediaMTX, only Relay's proxy does.
 */
function hlsLines(hlsPort: number | null): string[] {
  if (hlsPort === null) return ['hls: false'];
  return [
    'hls: true',
    `hlsAddress: ${q(`127.0.0.1:${hlsPort}`)}`,
    'hlsEncryption: false',
    'hlsAllowOrigins: []',
    'hlsTrustedProxies: []',
    'hlsAlwaysRemux: false',
    'hlsVariant: lowLatency',
    'hlsSegmentCount: 7',
    'hlsSegmentDuration: 1s',
    'hlsPartDuration: 200ms',
    'hlsSegmentMaxSize: 50M',
    'hlsDirectory: ""',
    `hlsMuxerCloseAfter: ${HLS_MUXER_CLOSE_AFTER_SEC}s`,
  ];
}

/** An HLS muxer stops this long after the last request (the last viewer left). */
export const HLS_MUXER_CLOSE_AFTER_SEC = 30;
